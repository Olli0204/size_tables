    public function __construct(private readonly DbInterface $db) {}

    public function deleteAll(): int
    {
        $deleted = 0;
        foreach (\array_merge($this->getBootData(), $this->getBindingData()) as $entry) {
            $row = $this->db->select('size_tables_data', ['name', 'hersteller'], [$entry['name'], $entry['hersteller']]);
            if ($row !== null && $row !== false) {
                $this->db->delete('size_tables_data', 'id', (int)$row->id);
                $deleted++;
            }
        }
        return $deleted;
    }

    public function insertAll(int $kWarengruppeSchuhe1, int $kWarengruppeSchuhe2, int $kWarengruppeBindungen): array
    {
        $result = ['schuhe' => 0, 'bindungen' => 0, 'skipped' => 0];

        $wgSchuhe = \implode(',', \array_filter([$kWarengruppeSchuhe1, $kWarengruppeSchuhe2]));

        foreach ($this->getBootData() as $entry) {
            $entry['kWarengruppe'] = $wgSchuhe;
            if ($this->exists($entry['name'], $entry['hersteller'])) {
                $result['skipped']++;
                continue;
            }
            $this->insert($entry);
            $result['schuhe']++;
        }

        foreach ($this->getBindingData() as $entry) {
            $entry['kWarengruppe'] = $kWarengruppeBindungen;
            if ($this->exists($entry['name'], $entry['hersteller'])) {
                $result['skipped']++;
                continue;
            }
            $this->insert($entry);
            $result['bindungen']++;
        }

        return $result;
    }

    private function exists(string $name, string $hersteller): bool
    {
        $row = $this->db->select('size_tables_data', ['name', 'hersteller'], [$name, $hersteller]);
        return $row !== false && $row !== null;
    }

    private function insert(array $entry): void
    {
        $obj              = new \stdClass();
        $obj->name        = $entry['name'];
        $obj->hersteller  = $entry['hersteller'];
        $obj->typ         = $entry['typ'];
        $obj->geschlecht  = $entry['geschlecht'];
        $obj->kWarengruppe = (string)$entry['kWarengruppe'];
        $obj->inhalt      = \json_encode($entry['inhalt'], \JSON_UNESCAPED_UNICODE);
        $this->db->insert('size_tables_data', $obj);
    }

